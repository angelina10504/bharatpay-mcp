FIXTURE = Path(__file__).resolve().parents[1] / 'tests/fixtures/nav_synthetic.txt'
CONTENT = FIXTURE.read_bytes()


@asynccontextmanager
async def database(url):
    store = Store(url)
    name = 'bharatpay_nav_test_' + uuid4().hex
    store.db = store.client[name]
    await store.start()
    try:
        yield store
    finally:
        # Drop ONLY the database generated by this invocation, including after a
        # client-disconnection test. Never use MONGO_DATABASE for cleanup.
        cleanup = Store(url)
        try:
            await cleanup.client.drop_database(name)
        finally:
            await cleanup.close()
            await store.close()


def source(content=CONTENT):
    return httpx.AsyncClient(transport=httpx.MockTransport(lambda request: httpx.Response(200, content=content)))


async def seed_lease(store, *, job=None, seconds=120):
    run = await store.insert('ingestion_runs', {'status': 'starting', 'started_at': now()})
    lease = NavLease(store, run['_id'], job=job, seconds=seconds)
    await lease.acquire()
    return lease


async def expect_error(awaitable, category):
    try:
        await awaitable
    except IngestionError as error:
        assert error.category == category, (category, error.category)
    else:
        raise AssertionError('Expected ' + category)


async def replay_and_metadata(url):
    async with database(url) as store, source() as client:
        first = await ingest_nav(store, client, trigger='airflow')
        second = await ingest_nav(store, client, fixture=FIXTURE)
        assert first['run_id'] != second['run_id']
        assert (first['accepted'], first['parsed_count'], first['rejected_count']) == (2, 3, 1)
        assert (first['upserted_count'], first['matched_count']) == (2, 0)
        assert (second['upserted_count'], second['matched_count'], second['modified_count']) == (0, 2, 2)
        assert first['source_sha256'] == second['source_sha256'] == hashlib.sha256(CONTENT).hexdigest()
        assert first['source_bytes'] == len(CONTENT)
        assert first['trigger'] == 'airflow' and second['trigger'] == 'cli'
        assert second['source_kind'] == 'fixture'
        assert first['source_date_min'] == '2026-11-02' and first['source_date_max'] == '2026-11-03'
        assert first['finished_at'] >= first['started_at'] and first['duration_seconds'] >= 0
        assert await store.db.nav_snapshots.count_documents({}) == 2
        snapshot = await store.db.nav_snapshots.find_one({'scheme_code': '990001'})
        assert snapshot['date'] == '2026-11-02' and snapshot['ingested_at'] >= snapshot['fetched_at']
        indexes = await store.db.nav_snapshots.index_information()
        assert indexes['scheme_code_1_date_1']['unique']


async def bad_feeds(url):
    for content in (b'<html>unavailable</html>', b'990001;-;-;Bad;NaN;03-Nov-2026\n', b''):
        async with database(url) as store, source(content) as client:
            await expect_error(ingest_nav(store, client), 'parse')
            run = await store.db.ingestion_runs.find_one({})
            assert run['status'] == 'failed' and run['accepted'] == 0
            assert run['source_sha256'] == hashlib.sha256(content).hexdigest()
            assert run['source_complete'] is True
            assert await store.db.nav_snapshots.count_documents({}) == 0
    async with database(url) as store, source() as client:
        await expect_error(ingest_nav(store, client, rules=QualityRules(max_rejected_fraction=0)), 'quality')
        run = await store.db.ingestion_runs.find_one({})
        assert run['accepted'] == 2 and run['upserted_count'] == 0


async def bulk_failures(url):
    # Mongo's real validator fails one operation in an unordered bulk. The whole
    # current transaction must abort, even if an earlier operation succeeded.
    for batch_size, committed in ((1000, 0), (1, 1)):
        async with database(url) as store, source() as client:
            await store.db.command('collMod', 'nav_snapshots', validator={'scheme_code': {'$ne': '990002'}})
            await expect_error(ingest_nav(store, client, batch_size=batch_size), 'write')
            run = await store.db.ingestion_runs.find_one({})
            assert run['status'] == 'failed' and run['accepted'] == 2
            assert run['upserted_count'] == run['batches_committed'] == committed
            assert await store.db.nav_snapshots.count_documents({}) == committed
            await store.db.command('collMod', 'nav_snapshots', validator={})
            retried = await ingest_nav(store, client)
            assert retried['matched_count'] == committed and retried['upserted_count'] == 2 - committed


async def concurrent_entrypoints(url):
    entered, resume = asyncio.Event(), asyncio.Event()
    async def slow(request):
        entered.set()
        await resume.wait()
        return httpx.Response(200, content=CONTENT)
    async with database(url) as store, httpx.AsyncClient(transport=httpx.MockTransport(slow)) as airflow, source() as worker:
        task = asyncio.create_task(ingest_nav(store, airflow, trigger='airflow'))
        await asyncio.wait_for(entered.wait(), 5)
        await store.insert('batch_jobs', {'kind': 'ingest_nav', 'status': 'queued', 'attempts': 0, 'owner_id': 'synthetic'})
        job = await store.claim()
        try:
            await process_job(store, worker, job)
            pending = await store.db.batch_jobs.find_one({'_id': job['_id']})
            assert pending['status'] == 'queued' and pending['attempts'] == 0
            assert await store.db.nav_snapshots.count_documents({}) == 0
        finally:
            resume.set()
        assert (await task)['status'] == 'completed'
        await store.db.batch_jobs.update_one({'_id': job['_id']}, {'$set': {'available_at': EPOCH}})
        await process_job(store, worker, await store.claim())
        completed = await store.db.batch_jobs.find_one({'_id': job['_id']})
        assert completed['status'] == 'completed' and completed['summary']['matched_count'] == 2
        assert completed['summary']['upserted_count'] == 0
        run = await store.db.ingestion_runs.find_one({'_id': completed['summary']['run_id']})
        assert run['status'] == completed['status'] == 'completed'


async def claims_and_stale_writers(url):
    async with database(url) as store:
        await store.insert('batch_jobs', {'kind': 'validate_csv', 'status': 'queued', 'attempts': 0})
        jobs = await asyncio.gather(*(store.claim() for _ in range(12)))
        assert len([job for job in jobs if job]) == 1
        runs = [await store.insert('ingestion_runs', {'status': 'starting', 'started_at': now()}) for _ in range(8)]
        leases = [NavLease(store, run['_id']) for run in runs]
        results = await asyncio.gather(*(lease.acquire() for lease in leases), return_exceptions=True)
        assert sum(result is None for result in results) == 1, results
        assert all(result is None or isinstance(result, IngestionBusy) for result in results), results
        old = next(lease for lease in leases if lease.version is not None)
        old_version = old.version
        # Start an old snapshot transaction before the takeover. A later guard
        # must conflict, rather than authorize from that stale transaction view.
        async with store.client.start_session() as session:
            async with await session.start_transaction():
                await store.db.nav_coordination.find_one({'_id': LEASE_ID}, session=session)
                await store.db.nav_coordination.update_one({'_id': LEASE_ID}, {'$set': {'lease_until': EPOCH}})
                new = await seed_lease(store)
                assert new.version > old_version
                try:
                    await old.guard(session)
                except (OperationFailure, LeaseLost):
                    pass
                else:
                    raise AssertionError('Stale transaction guard succeeded')
                await session.abort_transaction()
        called = False
        async def forbidden(session):
            nonlocal called
            called = True
            await store.db.nav_snapshots.insert_one({'scheme_code': 'stale', 'date': '2026-11-03'}, session=session)
        await expect_error(old.fenced(forbidden), 'lease_lost')
        assert not called and await store.db.nav_snapshots.count_documents({}) == 0
        await old.release()
        assert (await store.db.nav_coordination.find_one({'_id': LEASE_ID}))['owner'] == new.run_id
        old_run = await store.db.ingestion_runs.find_one({'_id': old.run_id})
        assert old_run['status'] == 'interrupted' and old_run['finished_at']
        assert (await store.db.nav_coordination.find_one({'_id': LEASE_ID}))['reclaims'] == 1
        await new.release()


async def expired_worker_token(url):
    async with database(url) as store:
        await store.insert('batch_jobs', {'kind': 'ingest_nav', 'status': 'queued', 'attempts': 0})
        first = await store.claim()
        old = await seed_lease(store, job=first)
        await store.db.batch_jobs.update_one({'_id': first['_id']}, {'$set': {'lease_until': EPOCH}})
        second = await store.claim()
        assert second['lease_token'] != first['lease_token'] and second['lease_reclaims'] == 1
        async def write(session):
            await store.db.nav_snapshots.insert_one({'scheme_code': 'stale', 'date': '2026-11-03'}, session=session)
        await expect_error(old.fenced(write), 'lease_lost')
        assert await store.db.nav_snapshots.count_documents({}) == 0
        await old.release()


async def ordered_commit_and_reconciliation(url):
    async with database(url) as store:
        old = await seed_lease(store, seconds=1)
        async with store.client.start_session() as session:
            async with await session.start_transaction():
                await old.guard(session)
                await store.db.nav_snapshots.insert_one({'scheme_code': '990001', 'date': '2026-11-03', 'nav': '1'}, session=session)
                await asyncio.sleep(1.1)
                takeover = asyncio.create_task(seed_lease(store))
                await asyncio.sleep(0.05)
                assert not takeover.done(), 'Takeover cannot pass an uncommitted fence write'
                await session.commit_transaction()
        new = await takeover
        assert new.version > old.version
        async def stale_write(session):
            await store.db.nav_snapshots.update_one({'scheme_code': '990001'}, {'$set': {'nav': '999'}}, session=session)
        await expect_error(old.fenced(stale_write), 'lease_lost')
        assert (await store.db.nav_snapshots.find_one({}))['nav'] == '1'
        # Reconciliation must not invalidate a live lease.
        assert await reconcile_nav_runs(store) == 0
        await store.db.nav_coordination.update_one({'_id': LEASE_ID}, {'$set': {'lease_until': EPOCH}})
        assert await reconcile_nav_runs(store) == 1
        await expect_error(new.fenced(stale_write), 'lease_lost')
        assert (await store.db.ingestion_runs.find_one({'_id': new.run_id}))['status'] == 'interrupted'
        orphan = await store.insert('ingestion_runs', {'status': 'starting', 'created_at': now() - timedelta(minutes=5)})
        assert await reconcile_nav_runs(store) == 1
        assert (await store.db.ingestion_runs.find_one({'_id': orphan['_id']}))['duration_seconds'] >= 300


async def renewal_and_cancellation(url):
    entered = asyncio.Event()
    async def slow(request):
        entered.set()
        await asyncio.sleep(1.5)
        return httpx.Response(200, content=CONTENT)
    async with database(url) as store, httpx.AsyncClient(transport=httpx.MockTransport(slow)) as client:
        result = await ingest_nav(store, client, lease_seconds=1)
        assert result['status'] == 'completed'  # several heartbeat renewals
        task = asyncio.create_task(ingest_nav(store, client, lease_seconds=1))
        entered.clear()
        await asyncio.wait_for(entered.wait(), 5)
        task.cancel()
        try:
            await task
        except asyncio.CancelledError:
            pass
        else:
            raise AssertionError('Cancellation swallowed')
        assert await store.db.ingestion_runs.count_documents({'status': 'interrupted'}) == 1
        assert (await store.db.nav_coordination.find_one({'_id': LEASE_ID}))['owner'] is None


async def disconnect_and_reconcile(url):
    async with database(url) as store:
        async def disconnected(request):
            await store.close()  # real client disconnect, not a mocked DB result
            return httpx.Response(200, content=CONTENT)
        async with httpx.AsyncClient(transport=httpx.MockTransport(disconnected)) as client:
            await expect_error(ingest_nav(store, client), 'database')
        replacement = Store(url)
        replacement.db = replacement.client[store.db.name]
        try:
            run = await replacement.db.ingestion_runs.find_one({})
            assert run['status'] == 'running'  # failure metadata could not be saved
            assert await replacement.db.nav_snapshots.count_documents({}) == 0
            await replacement.db.nav_coordination.update_one({'_id': LEASE_ID}, {'$set': {'lease_until': EPOCH}})
            async with source() as client:
                assert (await ingest_nav(replacement, client))['status'] == 'completed'
            old = await replacement.db.ingestion_runs.find_one({'_id': run['_id']})
            assert old['status'] == 'interrupted' and old['error_category'] == 'interrupted'
        finally:
            await replacement.close()


async def oversize_and_metrics(url):
    class Stream(httpx.AsyncByteStream):
        reads = 0
        closed = False
        async def __aiter__(self):
            for _ in range(100):
                self.reads += 1
                yield b'x' * 32768
        async def aclose(self):
            self.closed = True
    async with database(url) as store:
        stream = Stream()
        async with httpx.AsyncClient(transport=httpx.MockTransport(lambda request: httpx.Response(200, stream=stream))) as client:
            with patch.dict(os.environ, {'NAV_MAX_SOURCE_BYTES': '40000'}):
                await expect_error(ingest_nav(store, client), 'source_size')
        assert stream.reads == 2 and stream.closed
        run = await store.db.ingestion_runs.find_one({})
        assert run['source_sha256'] is None and run['source_bytes'] is None and not run['source_complete']
        metrics = await ingestion_metrics(store)
        assert metrics['last_completed'] is None and metrics['consecutive_failures'] == 1
        async with source() as client:
            await ingest_nav(store, client)
        metrics = await ingestion_metrics(store)
        assert metrics['consecutive_failures'] == 0
        assert metrics['last_completed']['upserted_count'] == 2
        assert metrics['last_completed']['source_sha256'] == hashlib.sha256(CONTENT).hexdigest()
        assert metrics['transaction_capable'] and metrics['lease']['owner_run_id'] is None
        async with source(b'') as client:
            await expect_error(ingest_nav(store, client), 'parse')
        metrics = await ingestion_metrics(store)
        assert metrics['consecutive_failures'] == 1 and metrics['last_failure']['error_category'] == 'parse'
        assert metrics['source_freshness_days'] is not None and metrics['last_completed_age_seconds'] >= 0
        # Old run counters must stay unknown in last-run views, rather than being
        # invented from accepted source rows.
        legacy = await store.insert('ingestion_runs', {'status': 'completed', 'finished_at': now(), 'accepted': 100})
        metrics = await ingestion_metrics(store)
        assert metrics['last_completed']['run_id'] == legacy['_id']
        assert metrics['last_completed']['upserted_count'] is None and metrics['legacy_runs_without_write_counts'] == 1


async def standalone_rejection(url):
    async with database(url) as store:
        hello = await store.db.command('hello')
        assert 'setName' not in hello, 'Use an isolated standalone server for this check'
        def forbidden(request):
            raise AssertionError('Standalone must fail before downloading')
        async with httpx.AsyncClient(transport=httpx.MockTransport(forbidden)) as client:
            await expect_error(ingest_nav(store, client), 'topology')
        run = await store.db.ingestion_runs.find_one({})
        assert run['status'] == 'failed' and run['error_category'] == 'topology'
        assert await store.db.nav_snapshots.count_documents({}) == 0
        assert not (await ingestion_metrics(store))['transaction_capable']
    print('PASS NAV: actual standalone MongoDB fails closed before source or snapshot writes')


async def run_nav_checks(url):
    # The replica-set requirement is checked by ingestion itself; refuse to
    # downgrade the tests silently when pointed at a standalone server.
    checks = [replay_and_metadata, bad_feeds, bulk_failures, concurrent_entrypoints,
              claims_and_stale_writers, expired_worker_token, ordered_commit_and_reconciliation,
              renewal_and_cancellation, disconnect_and_reconcile, oversize_and_metrics]
    for check in checks:
        await asyncio.wait_for(check(url), 45)
        print('PASS NAV:', check.__name__)
    return len(checks)


